/// Merkmale für die Fisch-Bestimmungshilfe.
enum KoerperForm {
  lang('Lang wie eine Schlange'),
  schlank('Schlank / spindelförmig'),
  hoch('Hochrückig / seitlich flach');

  const KoerperForm(this.text);
  final String text;
}

enum Groesse {
  klein('Klein (unter 20 cm)'),
  mittel('Mittel (20–60 cm)'),
  gross('Groß (über 60 cm)');

  const Groesse(this.text);
  final String text;
}

class Bestimmung {
  const Bestimmung(
    this.form, {
    required this.fettflosse,
    required this.barteln,
    required this.stachel,
    required this.saugscheibe,
    required this.groesse,
    required this.rot,
    required this.muster,
  });

  final KoerperForm form;

  /// Kleine Flosse ohne Strahlen zwischen Rücken- und Schwanzflosse.
  final bool fettflosse;

  /// Anzahl Barteln (0, 2, 4 oder 6 = sechs und mehr).
  final int barteln;

  /// Stachelige (harte) vordere Rückenflosse.
  final bool stachel;

  /// Bauchflossen zu einer Saugscheibe verwachsen (Grundeln).
  final bool saugscheibe;

  /// Größe ausgewachsener Fische.
  final Groesse groesse;

  /// Rote oder orange Flossen, Augen oder Punkte.
  final bool rot;

  /// Deutliche Punkte, Flecken, Streifen oder Marmorierung.
  final bool muster;
}

